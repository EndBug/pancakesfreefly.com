/**
 * Generates SVG path data for "PanCakes Freefly" for the hero handwritten animation.
 *
 * Usage:
 *   node scripts/generate-hero-svg.mjs
 *
 * Uses public/fonts/Romana Pro.ttf (or RomanaPro.ttf / .otf) for exact brand font.
 * Fallback: Caveat from Google Fonts if no local font found.
 */

import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const opentype = require("opentype.js");

const TEXT = "PanCakes Freefly";
const FONT_SIZE = 72;

const FONT_PATHS = [
  join(__dirname, "../public/fonts/RomanaPro.ttf"),
  join(__dirname, "../public/fonts/Romana Pro.ttf"),
  join(__dirname, "../public/fonts/RomanaPro.otf"),
];

const FALLBACK_FONT_URL =
  "https://github.com/google/fonts/raw/main/ofl/caveat/Caveat-Regular.ttf";

async function loadFont() {
  const fs = await import("node:fs");
  for (const p of FONT_PATHS) {
    if (fs.existsSync(p)) {
      console.log(">>> Using local font:", p);
      return opentype.loadSync(p);
    }
  }
  console.log(">>> Fetching fallback font (Caveat)...");
  const res = await fetch(FALLBACK_FONT_URL);
  if (!res.ok) throw new Error(`Font fetch failed: ${res.status}`);
  const buf = await res.arrayBuffer();
  return opentype.parse(buf);
}

async function run() {
  const font = await loadFont();
  // getPaths returns one path per glyph so we can animate letter-by-letter
  const paths = font.getPaths(TEXT, 0, 0, FONT_SIZE, {});

  const pathDataList = [];
  const pathBoxes = [];

  // Use 4 decimal places and force explicit L before Z so contours close with exact start coords
  const DECIMAL_PLACES = 2;
  function floatToString(v) {
    return Math.round(v) === v
      ? String(Math.round(v))
      : v.toFixed(DECIMAL_PLACES);
  }
  function packValues(...values) {
    let s = "";
    for (let i = 0; i < values.length; i += 1) {
      const v = values[i];
      if (v >= 0 && i > 0) s += " ";
      s += floatToString(v);
    }
    return s;
  }
  for (const path of paths) {
    let d = "";
    let contourStartX = 0;
    let contourStartY = 0;
    for (const cmd of path.commands) {
      if (cmd.type === "M") {
        contourStartX = cmd.x;
        contourStartY = cmd.y;
        d += "M" + packValues(cmd.x, cmd.y);
      } else if (cmd.type === "L") {
        d += "L" + packValues(cmd.x, cmd.y);
      } else if (cmd.type === "C") {
        d += "C" + packValues(cmd.x1, cmd.y1, cmd.x2, cmd.y2, cmd.x, cmd.y);
      } else if (cmd.type === "Q") {
        d += "Q" + packValues(cmd.x1, cmd.y1, cmd.x, cmd.y);
      } else if (cmd.type === "Z") {
        // Emit only explicit L to contour start (no Z). Having both L and Z creates
        // two path "ends" at the same point, so the stroke renderer can draw two
        // caps and leave a visible gap. Ending with L start start closes the contour
        // (last point = first point) with a single path end.
        d += "L" + packValues(contourStartX, contourStartY);
      }
    }
    pathDataList.push(d);
    pathBoxes.push(path.getBoundingBox());
  }

  // Split at space: "PanCakes" (0..spaceIdx-1) and "Freefly" (spaceIdx+1..end)
  const spaceIdx = pathDataList.findIndex((d) => d === "");
  if (spaceIdx < 0) throw new Error("Expected space glyph in path data");
  const line1PathData = pathDataList.slice(0, spaceIdx);
  const line2PathData = pathDataList.slice(spaceIdx + 1);

  function mergeBoxes(boxes) {
    const valid = boxes.filter(Boolean);
    if (valid.length === 0) return null;
    return {
      x1: Math.min(...valid.map((b) => b.x1)),
      y1: Math.min(...valid.map((b) => b.y1)),
      x2: Math.max(...valid.map((b) => b.x2)),
      y2: Math.max(...valid.map((b) => b.y2)),
    };
  }

  const padding = 10;
  function boxToViewBox(box) {
    if (!box) return "0 0 1 1";
    const w = box.x2 - box.x1 + padding * 2;
    const h = box.y2 - box.y1 + padding * 2;
    return `${box.x1 - padding} ${-box.y2 - padding} ${w} ${h}`;
  }

  const line1Box = mergeBoxes(pathBoxes.slice(0, spaceIdx));
  const line2Box = mergeBoxes(pathBoxes.slice(spaceIdx + 1));
  const heroTitleLine1ViewBox = boxToViewBox(line1Box);
  const heroTitleLine2ViewBox = boxToViewBox(line2Box);

  const outDir = join(__dirname, "../src/_generated");
  const outPath = join(outDir, "hero-title-paths.ts");
  mkdirSync(outDir, { recursive: true });
  const content = `/**
 * Generated by scripts/generate-hero-svg.mjs
 * Path data for "PanCakes" and "Freefly" as separate SVGs (own viewBox each).
 */

export const heroTitleLine1PathData: string[] = ${JSON.stringify(line1PathData, null, 2)};

export const heroTitleLine1ViewBox = ${JSON.stringify(heroTitleLine1ViewBox)};

export const heroTitleLine2PathData: string[] = ${JSON.stringify(line2PathData, null, 2)};

export const heroTitleLine2ViewBox = ${JSON.stringify(heroTitleLine2ViewBox)};
`;

  writeFileSync(outPath, content, "utf8");
  console.log(">>> Wrote", outPath);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
